//######################################################################################################
//# Sheena - Force Seal Damage
//# Adds three non-knockback hits to Force Seal against its current target.
//# Retains the original Force Seal program and tracks the target position.
//######################################################################################################
[ENABLE]

//################################################
//# Original instructions
//################################################

assert(TOS.exe+0x255D5,8B 14 85 64 66 8E 00 8B 34 8A)
assert(TOS.exe+0xA6DA,C7 46 18 F0 A6 40 00)

//################################################
//# Memory allocations
//################################################

alloc(mem_force_seal_code,0x400)
alloc(mem_force_seal_records,0x200)
alloc(mem_force_seal_state,0x10)

//################################################
//# Function and return addresses
//################################################

define(ForceSealOriginalProgram,TOS.exe+0xA6F0)
define(ForceSealLoadReturn,TOS.exe+0x255DF)

//################################################
//# Symbols
//################################################

registersymbol(fsB)
registersymbol(fsC)
registersymbol(fsActor)

//################################################
//# Force Seal hit and damage list substitution
//################################################

mem_force_seal_code:

ForceSealLoadHook:
  cmp ecx,0x1A6
  jne ForceSealLoadOriginal
  mov dword ptr [ebp+0x20],fsB
  mov dword ptr [ebp+0x28],fsC

ForceSealLoadOriginal:
  mov edx,[eax*4+TOS.exe+0x4E6664]
  mov esi,[edx+ecx*4]
  jmp ForceSealLoadReturn

//################################################
//# Force Seal program and target tracking
//################################################

fsProgram:
  push ebp
  mov ebp,esp
  push ebx
  push esi
  push edi

  mov esi,[ebp+0x08]
  mov [fsActor],esi

  push esi
  call ForceSealOriginalProgram
  add esp,0x04

  mov ebx,[esi+0x1396C]
  test ebx,ebx
  jz ForceSealProgramDone

  mov eax,[ebx+0x13938]
  mov [esi+0x13938],eax
  mov eax,[ebx+0x1393C]
  mov [esi+0x1393C],eax
  mov eax,[ebx+0x13940]
  mov [esi+0x13940],eax

ForceSealProgramDone:
  pop edi
  pop esi
  pop ebx
  pop ebp
  ret

//################################################
//# Install hooks
//################################################

TOS.exe+0x255D5:
  jmp ForceSealLoadHook
  nop #5

TOS.exe+0xA6DA:
  mov dword ptr [esi+0x18],fsProgram

//################################################
//# Hit records (0x20 bytes each)
//################################################

mem_force_seal_records:

fsB:
  db 0x0C,0x00,0x06,0x01,0xFF,0x00,0x00,0x00,0x00,0x00,0xF0,0x41,0x00,0x00,0xF0,0x41
  db 0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00
  db 0x18,0x00,0x06,0x01,0xFF,0x00,0x00,0x00,0x00,0x00,0xF0,0x41,0x00,0x00,0xF0,0x41
  db 0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00
  db 0x24,0x00,0x06,0x01,0xFF,0x00,0x00,0x00,0x00,0x00,0xF0,0x41,0x00,0x00,0xF0,0x41
  db 0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00
  db 0xFF,0xFF,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00
  db 0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00

//################################################
//# Damage records (0x1C bytes each)
//################################################

fsC:
  db 0x20,0x00,0x00,0x28,0x1E,0x01,0x01,0x01,0x00,0x00,0x00,0x00,0x00,0x01
  db 0x5A,0x00,0x00,0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00
  db 0x20,0x00,0x05,0x28,0x1E,0x0A,0x00,0x02,0x00,0x00,0x00,0x00,0x00,0x01
  db 0x32,0x00,0x00,0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00

//################################################
//# Current caster pointer (writable state)
//################################################

mem_force_seal_state:

fsActor:
  dd 0x00000000
